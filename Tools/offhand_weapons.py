"""offhand_weapons.py - turned left-hand icons for every melee weapon (08.11.26)

For each weapon of Items.txt (Weapon, Weapon2, Weapon1or2; not blasters) its icon turned 90
degrees counter-clockwise is added to waffel.icons.lod as <icon>L (offhand_icons.rotated),
and General/MMMWE_OffhandWeapons.lua is written with the offsets that keep the grip where
the upright icon had it: the grip is guessed on the upright icon, at GRIP_Y of its height
(by skill), in the middle of the opaque pixels of that row.

    python offhand_weapons.py <ITEMS.txt> <out icons.lod> <in icons.lod> <lua out> <icons lods by priority...>
"""
import sys
import numpy as np
from offhand_icons import read_lod, rotated, write_lod
from artifact_icons import decode

GRIP_Y = {'Spear': 0.6, 'Staff': 0.55}
DEFAULT_GRIP_Y = 0.82

def main(items, out, base, lua, *lods):
    L = [{e[0].lower(): e[1] for e in read_lod(l)[1]} for l in lods]
    rows = [l.split('\t') for l in open(items, encoding='latin1', newline='').read().split('\r\n')]
    w = [r for r in rows if len(r) > 15 and r[0].isdigit() and r[4] in ('Weapon', 'Weapon2', 'Weapon1or2')
         and r[5] != 'Blaster' and r[1].lower() != 'null']
    head, ents = read_lod(base)
    names = {e[0].lower() for e in ents}
    done = {}
    out_rows = []
    for r in w:
        num, pic, skill = int(r[0]), r[1], r[5]
        key = pic.lower()
        src = next((x[key] for x in L if key in x), None)
        if src is None:
            print('no icon', num, pic); continue
        new = pic + 'L'
        if key not in done:
            blob, (w0, h0, w1, h1) = rotated(src, new, 90)
            idx, _ = decode(src)
            gy = min(h0 - 1, int(round(h0 * GRIP_Y.get(skill, DEFAULT_GRIP_Y))))
            cols = np.nonzero((idx[max(0, gy - 2):gy + 3] > 0).any(0))[0]
            gx = int(round(cols.mean())) if len(cols) else w0 // 2
            # (x, y) of the upright icon -> (y, w0 - 1 - x) of the turned one
            done[key] = (blob, gx - gy, gy - (w0 - 1 - gx), w1, h1)
            if new.lower() in names:
                ents = [e for e in ents if e[0].lower() != new.lower()]
            ents.append([new, blob, b'\0' * 8])
        _, dx, dy, w1, h1 = done[key]
        out_rows.append((num, new, dx, dy, w1, h1, r[2]))
    write_lod(head, ents, out)
    with open(lua, 'w', newline='\r\n') as f:
        f.write('''--[[
	MMMWE_OffhandWeapons.lua - every melee weapon in the left hand is drawn turned (08.11.26)

	As the pistols of MMMWE_Blasters.lua: the left-hand item's icon is <icon>L, the icon turned
	90 degrees counter-clockwise (waffel.icons.lod, made by Tools/offhand_weapons.py), moved by
	MF.BlasterSpecs.OffhandIconOffset[item] = {x, y} from the upright icon's place. The offsets
	below keep the guessed grip where it was; the Paperdoll Tuner moves them ("Left hand",
	saved as LeftX, LeftY in Data/Tables/Weapon positions.txt). The hand is drawn over the grip.
	A turned icon is kept inside the 640x480 screen (MMMWE_Blasters.lua).
	Generated by Tools/offhand_weapons.py.
--]]

local MF = Merge.Functions
if not MF.SetOffhandIcon then
	return
end

-- [item id] = {icon, x, y, width, height}
local ICONS = {
''')
        for num, new, dx, dy, w1, h1, name in out_rows:
            f.write('\t[%d] = {"%s", %d, %d, %d, %d},   -- %s\n' % (num, new, dx, dy, w1, h1, name))
        f.write('''}
MF.OffhandWeaponIcons = ICONS

for num, t in pairs(ICONS) do
	MF.SetOffhandIcon(num, t[1], t[2], t[3], t[4], t[5])
end
''')
    print(len(out_rows), 'weapons,', len(done), 'icons')

if __name__ == '__main__':
    main(*sys.argv[1:])
